#!/usr/bin/env python3
"""Generate 145M pretrain configs for the GPU count of the current host.

The run keeps **262,144 tokens per optimizer step** no matter how many GPUs are
available.  What changes with the GPU count is only how that budget is split:

* global micro-batch  ``micro = gpus * packs_per_rank * seq_len``
* gradient accumulation ``grad_accum = tokens_per_step // micro``

``packs_per_rank = max(1, per_rank_tokens // seq_len)`` mirrors the loader
(``size = max(1, per_rank_tokens // seq_len)``), which matters at 8K: a 4K
per-rank budget cannot hold a whole 8K pack, so each rank loads one 8192-token
pack and the 8K stage needs ``grad_accum 8`` instead of 16 to stay at 262k.

Usage::

    python scripts/autoconfig_145m.py                    # auto-detect GPUs
    python scripts/autoconfig_145m.py --gpus 8           # force a count
    python scripts/autoconfig_145m.py --dry-run          # print the table only
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BASE = "configs/pretrain/pretrain_145m.yaml"
DEFAULT_CURRICULUM = "configs/pretrain/curriculum_145m_4x4090.yaml"
HEADER = (
    "# GENERATED by scripts/autoconfig_145m.py -- do not edit by hand.\n"
    "# Tokens per optimizer step is fixed at {tps:,}; only micro-batch and\n"
    "# grad_accum change with the GPU count.\n"
)


def detect_gpus() -> int:
    try:
        import torch
    except ImportError:
        return 0
    return int(torch.cuda.device_count())


def plan_stage(stage: dict, gpus: int, per_rank: int, tokens_per_step: int) -> dict:
    seq_len = int(stage["seq_len"])
    packs = max(1, per_rank // seq_len)
    micro = gpus * packs * seq_len
    if tokens_per_step % micro:
        raise SystemExit(
            f"seq_len {seq_len}: micro-batch {micro} does not divide "
            f"{tokens_per_step:,} tokens/step; use a GPU count in {VALID_GPUS}"
        )
    return {
        "seq_len": seq_len,
        "packs_per_rank": packs,
        "micro": micro,
        "grad_accum": tokens_per_step // micro,
    }


VALID_GPUS = (1, 2, 4, 8, 16)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--gpus", type=int, default=None, help="default: torch.cuda.device_count()")
    ap.add_argument("--tokens-per-step", type=int, default=262_144)
    # 8192 tokens/rank keeps the 4K-stage peak at ~11.6 GiB on a 24 GB card
    # (measured on a 4090, fused attention, optimizer state included) and
    # amortises launch/sync overhead over twice as many tokens.  262,144 is
    # divisible by 8192, so every stage keeps grad_accum 32 on one GPU.
    ap.add_argument("--per-rank-tokens", type=int, default=8192)
    ap.add_argument("--base", default=DEFAULT_BASE)
    ap.add_argument("--curriculum", default=DEFAULT_CURRICULUM)
    ap.add_argument("--out-dir", default="configs/pretrain/generated")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gpus = args.gpus if args.gpus is not None else detect_gpus()
    if gpus <= 0:
        raise SystemExit("no CUDA device detected; pass --gpus N explicitly")

    base_path = ROOT / args.base
    curriculum_path = ROOT / args.curriculum
    base = yaml.safe_load(base_path.read_text(encoding="utf-8"))
    curriculum = yaml.safe_load(curriculum_path.read_text(encoding="utf-8"))

    plans = [plan_stage(stage, gpus, args.per_rank_tokens, args.tokens_per_step)
             for stage in curriculum["stages"]]

    print(f"gpus={gpus}  tokens/step={args.tokens_per_step:,}  per-rank={args.per_rank_tokens}")
    print(f"{'seq_len':>8} {'packs/rank':>10} {'micro(global)':>14} {'grad_accum':>10} {'tokens/step':>12}")
    for plan in plans:
        print(
            f"{plan['seq_len']:>8} {plan['packs_per_rank']:>10} {plan['micro']:>14,} "
            f"{plan['grad_accum']:>10} {plan['micro'] * plan['grad_accum']:>12,}"
        )

    out_dir = ROOT / args.out_dir
    out_base = out_dir / f"pretrain_145m_g{gpus}.yaml"
    out_curriculum = out_dir / f"curriculum_145m_g{gpus}.yaml"
    if args.dry_run:
        print(f"\nwould write {out_base.relative_to(ROOT)} and {out_curriculum.relative_to(ROOT)}")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)

    for stage, plan in zip(curriculum["stages"], plans, strict=True):
        stage["batch_tokens"] = plan["micro"]
        stage["batch_tokens_final"] = plan["micro"]
        stage["grad_accum"] = plan["grad_accum"]

    first = plans[0]
    base.setdefault("data", {})["batch_tokens"] = first["micro"]
    base["data"]["batch_tokens_final"] = first["micro"]
    base.setdefault("train", {})["grad_accum"] = first["grad_accum"]
    curriculum["base_config"] = str(out_base.relative_to(ROOT))

    spec = HEADER.format(tps=args.tokens_per_step)
    out_base.write_text(spec + yaml.safe_dump(base, sort_keys=False, allow_unicode=True), encoding="utf-8")
    out_curriculum.write_text(
        spec + yaml.safe_dump(curriculum, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )

    print(f"\nwrote {out_base.relative_to(ROOT)}")
    print(f"wrote {out_curriculum.relative_to(ROOT)}")
    print("\nlaunch:")
    print(f"  NPROC_PER_NODE={gpus} bash scripts/train_curriculum.sh {out_curriculum.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
