"""Heuristic quality filters for pretraining / SFT / code data.

These are deliberately cheap and inspectable.  Each document gets a score and a
list of rejection reasons; the pipeline can log both instead of silently
dropping data.
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from dataclasses import dataclass, field

_CJK_RE = re.compile(r"[\u4e00-\u9fff]")
_ALNUM_RE = re.compile(r"[A-Za-z0-9\u4e00-\u9fff]")
_SYMBOL_RE = re.compile(r"[^\sA-Za-z0-9\u4e00-\u9fff]")
_WORD_RE = re.compile(r"\S+")
_LICENSE_RE = re.compile(r"(?i)\b(MIT|Apache-2\.0|BSD-3-Clause|BSD-2-Clause|ISC|MPL-2\.0|Unlicense)\b")
_COPYLEFT_RE = re.compile(r"(?i)\b(GPL-2\.0|GPL-3\.0|AGPL-3\.0|LGPL|CC-BY-SA-4\.0)\b")
_AUTOGEN_RE = re.compile(
    r"(?i)(auto-?generated|generated by (a )?(script|tool|program)|do not edit|this file was generated)"
)
_TEMPLATE_PHRASES = (
    "lorem ipsum",
    "click here to",
    "all rights reserved",
    "cookie policy",
    "subscribe to our newsletter",
)


@dataclass
class QualityConfig:
    min_chars: int = 32
    max_chars: int = 1_000_000
    max_symbol_ratio: float = 0.45
    min_alnum_ratio: float = 0.30
    max_repeated_line_ratio: float = 0.30
    max_repeated_ngram_ratio: float = 0.20
    max_digit_ratio: float = 0.60
    min_code_line_chars: int = 4
    max_code_line_chars: int = 400
    license_allowlist: tuple[str, ...] = (
        "MIT",
        "Apache-2.0",
        "BSD-3-Clause",
        "BSD-2-Clause",
        "ISC",
        "MPL-2.0",
        "Unlicense",
    )
    reject_autogenerated_code: bool = True


@dataclass
class QualityResult:
    score: float
    reasons: list[str] = field(default_factory=list)
    metrics: dict[str, float] = field(default_factory=dict)

    @property
    def accepted(self) -> bool:
        return not self.reasons


def _repeated_ngram_ratio(text: str, n: int = 8) -> float:
    words = _WORD_RE.findall(text)
    if len(words) < n * 2:
        return 0.0
    grams = [tuple(words[i : i + n]) for i in range(len(words) - n + 1)]
    if not grams:
        return 0.0
    return 1.0 - len(set(grams)) / len(grams)


def _repeated_line_ratio(text: str) -> float:
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if not lines:
        return 0.0
    return 1.0 - len(set(lines)) / len(lines)


def score_text(text: str, *, domain: str = "general", config: QualityConfig | None = None) -> QualityResult:
    config = config or QualityConfig()
    reasons: list[str] = []
    chars = len(text)
    if chars < config.min_chars:
        reasons.append("too_short")
    if chars > config.max_chars:
        reasons.append("too_long")
    alnum = len(_ALNUM_RE.findall(text))
    symbols = len(_SYMBOL_RE.findall(text))
    digits = sum(char.isdigit() for char in text)
    total = max(chars, 1)
    metrics = {
        "chars": float(chars),
        "alnum_ratio": alnum / total,
        "symbol_ratio": symbols / total,
        "digit_ratio": digits / total,
        "repeated_line_ratio": _repeated_line_ratio(text),
        "repeated_ngram_ratio": _repeated_ngram_ratio(text),
    }
    if metrics["alnum_ratio"] < config.min_alnum_ratio:
        reasons.append("low_alnum_ratio")
    if metrics["symbol_ratio"] > config.max_symbol_ratio:
        reasons.append("too_many_symbols")
    if metrics["digit_ratio"] > config.max_digit_ratio:
        reasons.append("too_many_digits")
    if metrics["repeated_line_ratio"] > config.max_repeated_line_ratio:
        reasons.append("repeated_lines")
    if metrics["repeated_ngram_ratio"] > config.max_repeated_ngram_ratio:
        reasons.append("repeated_ngrams")
    lowered = text[:5000].lower()
    for phrase in _TEMPLATE_PHRASES:
        if phrase in lowered:
            reasons.append(f"template:{phrase}")
            break
    if domain == "code":
        lines = text.splitlines()
        too_long_lines = sum(len(line) > config.max_code_line_chars for line in lines)
        if lines and too_long_lines / len(lines) > 0.1:
            reasons.append("minified_code")
        if config.reject_autogenerated_code and _AUTOGEN_RE.search(text[:3000]):
            reasons.append("autogenerated_code")
    score = max(0.0, min(1.0, metrics["alnum_ratio"] * 1.2 - metrics["symbol_ratio"] * 0.5))
    return QualityResult(score=score, reasons=reasons, metrics=metrics)


def code_license_ok(text: str, *, config: QualityConfig | None = None) -> bool:
    """Reject files whose SPDX header is copyleft/unknown when a header is present."""
    config = config or QualityConfig()
    head = text[:2000]
    if _COPYLEFT_RE.search(head):
        return False
    match = _LICENSE_RE.search(head)
    if match:
        return match.group(1).lower() in {item.lower() for item in config.license_allowlist}
    # No header: accept (The Stack license metadata is supposed to filter this
    # upstream) but the pipeline records ``license=unknown``.
    return True


def filter_texts(
    texts: Iterable[str], *, domain: str = "general", config: QualityConfig | None = None
):
    """Yield ``(text, QualityResult)``; callers decide whether to drop."""
    for text in texts:
        yield text, score_text(text, domain=domain, config=config)
